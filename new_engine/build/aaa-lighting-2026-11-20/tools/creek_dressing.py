#!/usr/bin/env python3
"""Generate scenery/creek_dressing_instances.txt for the AAA candidate.

Reeds, tall grass, ferns and partly buried rocks along the authored creek
ribbons in world.studio. Positions follow the engine's own Catmull-Rom ribbon
sampling (world_surface_authoring.cpp bake_ribbon). Deterministic: the same
world.studio always yields the same file.  Usage: creek_dressing.py PROJECT_DIR
"""
import math, random, shlex, sys
from pathlib import Path

ATLAS_W, ATLAS_D = 100800.0, 56700.0
CREEKS = {'West woodland creek': 'woodland', 'Central meadow creek': 'meadow', 'Eastern forest creek': 'woodland'}

def ribbons(studio):
    out = []
    for line in open(studio):
        if not line.startswith('surfaces "ribbon'): continue
        t = shlex.split(shlex.split(line)[1])
        name, kind = t[1], int(t[2]); width, shoulder, depth, smooth, n = float(t[4]), float(t[5]), float(t[6]), int(t[7]), int(t[8])
        pts = [tuple(map(float, t[9 + 3*i: 12 + 3*i])) for i in range(n)]
        out.append(dict(name=name, kind=kind, width=width, shoulder=shoulder, smooth=smooth, samples=bake(pts, smooth)))
    return out

def bake(pts, smooth):
    s = [pts[0]]
    for i in range(len(pts) - 1):
        p0, p1, p2, p3 = pts[i-1 if i else i], pts[i], pts[i+1], pts[min(i+2, len(pts)-1)]
        count = max(1, math.ceil(math.hypot(p2[0]-p1[0], p2[2]-p1[2]) / 2))
        for k in range(1, count + 1):
            t = k / count
            c = lambda a, b, cc, z: .5*((2*b)+(-a+cc)*t+(2*a-5*b+4*cc-z)*t*t+(-a+3*b-3*cc+z)*t**3) if smooth else b+(cc-b)*t
            q = tuple(c(p0[j], p1[j], p2[j], p3[j]) for j in range(3))
            if math.hypot(q[0]-s[-1][0], q[2]-s[-1][2]) >= .01: s.append(q)
    return s

def nearest(samples, x, z):
    best = 1e30
    for a, b in zip(samples, samples[1:]):
        dx, dz = b[0]-a[0], b[2]-a[2]; n = dx*dx + dz*dz
        if n < 1e-12: continue
        t = max(0., min(1., ((x-a[0])*dx + (z-a[2])*dz) / n))
        best = min(best, math.hypot(x-a[0]-dx*t, z-a[2]-dz*t))
    return best

def walk(samples, step):
    """Yield (x, z, tangent_x, tangent_z, distance) every `step` metres."""
    acc, travelled = 0., 0.
    for a, b in zip(samples, samples[1:]):
        seg = math.hypot(b[0]-a[0], b[2]-a[2])
        if seg < 1e-6: continue
        tx, tz = (b[0]-a[0])/seg, (b[2]-a[2])/seg
        while acc <= seg:
            f = acc/seg
            yield a[0]+(b[0]-a[0])*f, a[2]+(b[2]-a[2])*f, tx, tz, travelled+acc
            acc += step
        acc -= seg; travelled += seg

def clump_field(rng_seed, length):
    rng = random.Random(rng_seed); knots = [rng.random() for _ in range(int(length/6)+3)]
    def f(d):
        i = int(d/6); u = d/6 - i; u = u*u*(3-2*u)
        return knots[i]*(1-u) + knots[i+1]*u
    return f

def main(project):
    project = Path(project)
    rib = ribbons(project/'world.studio')
    rivers = [r for r in rib if r['kind'] == 1]; roads = [r for r in rib if r['kind'] == 0]
    lines = ['# AAA candidate creek dressing: generated by tools/creek_dressing.py from world.studio ribbons. Do not edit by hand.']
    counts = {}
    seen = set()
    def emit(alias, x, z, yaw, scale, burial, wind):
        key = (alias, round(x*20), round(z*20))
        if key in seen: return
        seen.add(key)
        u, v = x/ATLAS_W + .5, z/ATLAS_D + .5
        rec = f'{alias} {u:.12f} {v:.12f} {yaw:.3f} {scale:.4f} {burial:.4f}' + (' wind 1 1' if wind else '')
        lines.append(rec); counts[alias] = counts.get(alias, 0) + 1
    def clear(x, z, keep_from):
        for r in rivers:
            if nearest(r['samples'], x, z) < r['width']*.5 + keep_from: return False
        for r in roads:
            if nearest(r['samples'], x, z) < r['width']*.5 + 3.0: return False
        return True
    for creek in rivers:
        habitat = CREEKS.get(creek['name'])
        if not habitat and 'great river' in creek['name']: habitat = 'river'
        if not habitat: continue
        step = 9.0 if habitat == 'river' else 1.1
        half = creek['width']*.5
        length = sum(math.hypot(b[0]-a[0], b[2]-a[2]) for a, b in zip(creek['samples'], creek['samples'][1:]))
        for side in (-1, 1):
            seed = sum(ord(c)*(i+1) for i, c in enumerate(creek['name'])) * 7 + (side+1)*977
            rng = random.Random(seed); reed_clumps = clump_field(seed+1, length); grass_clumps = clump_field(seed+2, length)
            for x, z, tx, tz, d in walk(creek['samples'], step):
                nx, nz = -tz*side, tx*side  # outward normal for this bank
                def place(offset, jitter):
                    along = (rng.random()-.5)*jitter
                    return x + nx*offset + tx*along, z + nz*offset + tz*along
                # Reeds: clumps along the waterline, gaps between.
                c = reed_clumps(d)
                if c > (.62 if habitat == 'river' else .55):
                    for _ in range(1 + (c > .66) + (c > .82)):
                        px, pz = place(half + .35 + rng.random()*1.25, 1.0)
                        if clear(px, pz, .3): emit('bep_nature_reed', px, pz, rng.uniform(-180, 180), rng.uniform(.75, 1.35), .02, True)
                # Tall grass on the bank slope, denser where reeds thin out.
                g = grass_clumps(d)
                for _ in range(0 if habitat == 'river' else (g > .42) + (g > .72)):
                    px, pz = place(half + 1.2 + rng.random()*4.2, 1.1)
                    if clear(px, pz, 1.0): emit('bep_nature_grass_long', px, pz, rng.uniform(-180, 180), rng.uniform(.8, 1.3), .02, True)
                # Woodland creeks: ferns on the upper bank.
                if habitat == 'woodland' and rng.random() < .45:
                    px, pz = place(half + 2.5 + rng.random()*4.0, 1.1)
                    if clear(px, pz, 2.0): emit('bep_nature_fern', px, pz, rng.uniform(-180, 180), rng.uniform(.7, 1.25), .02, True)
                # Rocks at the water's edge, partly buried; occasional pairs.
                if rng.random() < (.06 if habitat == 'river' else .085):
                    for k in range(1 + (rng.random() < .35)):
                        px, pz = place(half + .3 + rng.random()*1.6, 1.6)
                        if clear(px, pz, .25):
                            emit(f'rock{rng.randrange(3)}', px, pz, rng.uniform(-180, 180), rng.uniform(.25, .65), rng.uniform(.04, .14), False)
    # Forest-camp dressing around the arrival hearth: props in a ring outside
    # the fire/tent/traveler circle, then a thicker understorey band.
    cx, cz = -11988.0, 5172.0
    spawn = (-11988.0, 5180.0)  # opening.config meadow_spawn
    rng = random.Random(51720)
    props = ['purchased_prop_logs']*4 + ['purchased_crate']*2 + ['purchased_barrel', 'purchased_prop_barrel_small', 'purchased_prop_barrel_small'] + \
            ['purchased_prop_sack']*4 + ['bep_prop_chest', 'bep_prop_bucket', 'purchased_prop_rope', 'castle_residents_bedroll', 'castle_residents_bedroll']
    for k, alias in enumerate(props):
        a = k/len(props)*2*math.pi + rng.uniform(-.12, .12)
        r = rng.uniform(6.2, 9.5)
        px, pz = cx + math.cos(a)*r, cz + math.sin(a)*r
        if not clear(px, pz, .5) or math.hypot(px - spawn[0], pz - spawn[1]) < 4.5 or abs(px - cx) < 3.2 and pz > cz: continue
        emit(alias, px, pz, (math.degrees(-a) + rng.uniform(-25, 25) + 180) % 360 - 180, rng.uniform(.9, 1.1), 0, False)
    plants = [('bep_nature_bush_a', .9, 1.4), ('bep_nature_bush_b', .9, 1.4), ('bep_nature_fern', .8, 1.3), ('bep_nature_fern', .8, 1.3),
              ('bep_nature_grass_broad', .8, 1.3), ('bep_nature_grass_broad', .8, 1.3), ('bep_nature_clover', .8, 1.3)]
    for k in range(180):
        alias, lo, hi = plants[k % len(plants)]
        a = rng.uniform(0, 2*math.pi); r = 6.5 + (rng.random()**.8)*21.5
        x, z = cx + math.cos(a)*r, cz + math.sin(a)*r
        if clear(x, z, .5) and math.hypot(x - spawn[0], z - spawn[1]) > 3.0: emit(alias, x, z, rng.uniform(-180, 180), rng.uniform(lo, hi), .01 if 'clover' in alias else (.05 if 'bush' in alias else .02), True)
    # Grass verges along the arrival trail (camp -> town): the trail edge
    # gets broad and long verge grass so the dirt band does not read bare.
    rng = random.Random(4417)
    for road in roads:
        if road['name'] != 'Seldonne arrival road': continue
        half = road['width']*.5
        for x, z, tx, tz, d in walk(road['samples'], 1.5):
            for side in (-1, 1):
                nx, nz = -tz*side, tx*side
                off = half + .45 + rng.random()*1.3
                px, pz = x + nx*off + tx*(rng.random()-.5), z + nz*off + tz*(rng.random()-.5)
                if math.hypot(px - spawn[0], pz - spawn[1]) < 2.5: continue
                alias = 'opening_verge_grass_long' if rng.random() < .55 else 'opening_verge_grass_broad'
                emit(alias, px, pz, rng.uniform(-180, 180), rng.uniform(.8, 1.25), .02, True)
    out = project/'scenery/creek_dressing_instances.txt'
    out.write_text('\n'.join(lines) + '\n')
    print(out, sum(counts.values()), counts)

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1]/'world-project')
