#!/usr/bin/env python3
"""Bake conservative sole support for actual affine NPC pose pairs.

The minimum of affine vertex heights is concave. Linear interpolation between
sampled minima never subtracts more than the true contact height. Only renderer
roots move; navigation routes and logical support stay intact.
"""
from pathlib import Path
import argparse,hashlib,json
import numpy as np
from audit_village_pose_compatibility import ACTIVE,MODELS,ROOT,pose
TARGET=ROOT/'engine/world_village_contact_data.inc'
def build():
    groups=[];walks=[];files={};offset=0
    for prefix,name,walk,idle in ACTIVE:
        clips={mode:[pose(MODELS/f'{prefix}_{name}_{mode}_{i:02}.glb')for i in range(n)]for mode,n in [('walk',walk),('idle',idle)]if n}
        for mode in ['walk','idle']:
            frames=clips.get(mode,[])
            for i,a in enumerate(frames):groups.append((offset+i,offset+(i+1)%len(frames),a,frames[(i+1)%len(frames)]))
            if mode=='walk' and frames:walkbase=offset
            if mode=='idle':idlebase=offset
            offset+=len(frames)
        if walk:walks.extend([(idlebase,walkbase,clips['idle'][0],clips['walk'][0]),(walkbase,idlebase,clips['walk'][0],clips['idle'][0]),(walkbase+walk//2,idlebase,clips['walk'][walk//2],clips['idle'][0])])
    assert len(groups)==76;groups+=walks;assert len(groups)==91
    seated=[pose(MODELS/f'village_character_seated_idle_{i:02}.glb')for i in range(4)]
    groups += [(76+i,76+(i+1)%4,a,seated[(i+1)%4])for i,a in enumerate(seated)]
    rows=[];maximum_residual=0
    for ia,ib,a,b in groups:
        for p in [a,b]:files[p['file']]=hashlib.sha256((MODELS/p['file']).read_bytes()).hexdigest()
        curves=[]
        for t in np.linspace(0,1,33):
            low=min(float(((1-t)*(pa['world'][:,1]+a['raw_min_y'])+t*(pb['world'][:,1]+b['raw_min_y'])).min())for pa,pb in zip(a['records'],b['records']))
            assert -.0001<=low<=.05,(a['file'],b['file'],t,low)
            curves.append(max(0,int(low*1e7)/1e7))
        # Endpoint vertices above8cm cannot produce the minimum below5cm.
        contacts=[]
        for pa,pb in zip(a['records'],b['records']):
            ya=pa['world'][:,1]+a['raw_min_y'];yb=pb['world'][:,1]+b['raw_min_y']
            mask=(ya<.08)|(yb<.08)
            if mask.any():contacts.append((ya[mask],yb[mask]))
        for t in np.linspace(0,1,257):
            true_low=min(float(((1-t)*ya+t*yb).min())for ya,yb in contacts)
            baked=float(np.interp(t,np.linspace(0,1,33),curves))
            assert baked<=true_low+.000001,(ia,ib,t,baked,true_low)
            maximum_residual=max(maximum_residual,true_low-baked)
        rows.append((ia,ib,curves))
    text='// Generated by tools/build_village_contact_curves.py; actual source vertex minima.\nstatic constexpr float world_village_contact_curves[][33]={\n'
    for a,b,v in rows:text+='    {'+','.join(f'{x:.7f}f'for x in v)+'}, // '+str(a)+' -> '+str(b)+'\n'
    text+='};\n'
    assert maximum_residual<.003,maximum_residual
    return text,dict(maximum_residual_hover_m=maximum_residual,source_sha256=files,pairs=len(rows),samples_per_pair=33,maximum_offset_m=max(max(v)for _,_,v in rows),method='Conservative piecewise-linear lower envelope of actual affine vertex minima; no runtime geometry scan or skeletal IK')
def main():
    c=argparse.ArgumentParser();c.add_argument('--check',action='store_true');c.add_argument('--report',type=Path);a=c.parse_args();text,report=build()
    if a.check:assert TARGET.read_text()==text,'Contact table stale'
    else:TARGET.write_text(text)
    if a.report:a.report.write_text(json.dumps(report,indent=2)+'\n')
    print(f"PASS contact curves: {report['pairs']} actual pose pairs, maximum {report['maximum_offset_m']*1000:.2f} mm, fixed lookup only")
if __name__=='__main__':main()
