#!/usr/bin/env python3
"""Compile editable waystation terrain/route authoring into bounded C constants."""
import argparse, json, math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'projects/valwood_world/scenery/starting_area_layout.json'
PLACEMENTS=ROOT/'projects/valwood_world/scenery/starting_area_manifest.json'
OUTPUT=ROOT/'engine/world_starting_layout.inc'
def number(v):
    assert math.isfinite(v)
    return format(v,'.12g')
def row(values): return '{'+','.join(number(v) for v in values)+'}'
def validate(d):
    def vector(values,count):
        assert len(values)==count and all(isinstance(v,(int,float)) and math.isfinite(v) for v in values)
    o=d['origin'];b=d['bounds']
    for key in ['world_xz','right_xz','forward_xz']:vector(o[key],2)
    vector(b['min_rf'],2);vector(b['max_rf'],2)
    assert all(b['max_rf'][i]>b['min_rf'][i] for i in (0,1)) and b['feather_m']>0
    right=o['right_xz'];forward=o['forward_xz']
    assert abs(math.hypot(*right)-1)<1e-6 and abs(math.hypot(*forward)-1)<1e-6
    assert abs(sum(right[i]*forward[i] for i in (0,1)))<1e-6
    assert 0<=d['preserve']['spawn_radius_m']<20
    assert 0<len(d['pads'])<=32 and 0<len(d['paths'])<=16 and 0<len(d['clearings'])<=32
    for p in d['pads']:
        vector(p['center_rf'],2);vector(p['half_size_rf'],2);vector(p['slope_rf'],2)
        assert min(p['half_size_rf'])>0 and 0<p['feather_m']<=100 and math.isfinite(p['target_height_m'])
        if 'surface_half_size_rf' in p:
            vector(p['surface_half_size_rf'],2);assert min(p['surface_half_size_rf'])>0
    for p in d['paths']:
        points=p['points_rf'];assert 2<=len(points)<=128 and 0<p['half_width_m']<=20 and 0<p['feather_m']<=20
        for a in points:vector(a,2)
        assert all(math.dist(a,b)>.001 for a,b in zip(points,points[1:])),'Zero-length path segment'
    for c in d['clearings']:
        vector(c['center_rf'],2);vector(c['inner_radii_rf'],2);vector(c['outer_radii_rf'],2)
        assert all(0<c['inner_radii_rf'][i]<c['outer_radii_rf'][i] for i in (0,1))
def generate():
    d=json.loads(SOURCE.read_text());o=d['origin']; b=d['bounds']
    validate(d)
    corners=[(o['world_xz'][0]+r*o['right_xz'][0]+f*o['forward_xz'][0],o['world_xz'][1]+r*o['right_xz'][1]+f*o['forward_xz'][1]) for r in (b['min_rf'][0],b['max_rf'][0]) for f in (b['min_rf'][1],b['max_rf'][1])]
    xmin=min(p[0] for p in corners);zmin=min(p[1] for p in corners)
    bounds=[xmin,zmin,max(p[0] for p in corners)-xmin,max(p[1] for p in corners)-zmin]
    lines=['/* Generated by tools/build_starting_terrain.py; edit starting_area_layout.json. */',
        'static const double starting_origin[2]='+row(o['world_xz'])+';',
        'static const double starting_right[2]='+row(o['right_xz'])+';',
        'static const double starting_forward[2]='+row(o['forward_xz'])+';',
        'static const double starting_bounds[4]='+row(bounds)+';',
        'static const double starting_rf_bounds[4]='+row(b['min_rf']+b['max_rf'])+';',
        'static const double starting_edge_feather='+number(b['feather_m'])+';',
        'static const double starting_spawn_radius='+number(d['preserve']['spawn_radius_m'])+';',
        'static const StartingPad starting_pads[]={']
    for p in d['pads']:
        lines.append('    '+row(p['center_rf']+p['half_size_rf']+[p['target_height_m']]+p['slope_rf']+[p['feather_m'],int(p['material']=='stone_gravel')]+p.get('surface_half_size_rf',p['half_size_rf']))+',')
    lines+=['};','static const StartingPath starting_paths[]={']
    for p in d['paths']:
        for a,c in zip(p['points_rf'],p['points_rf'][1:]):lines.append('    '+row(a+c+[p['half_width_m'],p['feather_m']])+',')
    lines+=['};','static const StartingClearing starting_clearings[]={']
    for c in d['clearings']:lines.append('    '+row(c['center_rf']+c['inner_radii_rf']+c['outer_radii_rf'])+',')
    lines+=['};','static const StartingExclusion starting_no_grass[]={']
    placements=json.loads(PLACEMENTS.read_text())
    for p in placements['records']:
        if p['alias'] not in ['starting_platform','starting_table','starting_firepit','starting_stump','starting_crate','starting_barrel','starting_wall']:continue
        low,high=placements['actual_glb_bounds'][p['alias']]
        yaw=math.radians(o['model_yaw_for_right_degrees']+p['heading']);scale=p['scale']
        lines.append('    '+row([p['x'],p['z'],low[0]*scale,high[0]*scale,low[2]*scale,high[2]*scale,math.cos(yaw),math.sin(yaw)])+',')
    return '\n'.join(lines+['};',''])
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();data=generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text()!=data: raise SystemExit('Starting terrain constants are stale; run tools/build_starting_terrain.py')
        print('Starting terrain constants match editable layout.')
    else:OUTPUT.write_text(data);print(OUTPUT.relative_to(ROOT))
if __name__=='__main__':main()
