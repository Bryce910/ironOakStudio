#!/usr/bin/env python3
"""Generate the fixed village-life extension. No models, scenery or settings IO.

python3 tools/build_village_life.py --check
The checked-in JSON is the editable authoring source; --check rejects stale
generated data. New definitions append after all128 original residents.
"""
import argparse
import json
import math
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'projects/valwood_world/scenery/village_life_layout.json'
TARGET=ROOT/'engine/world_village_life_data.inc'


def generate():
    data=json.loads(SOURCE.read_text())
    records=data['residents']
    assert data['original_residents']==128 and data['added_residents']==len(records)==12
    assert sum(r['seated']for r in records)==4 and sum(r['walker']for r in records)==3
    assert {name:sum(r['district']==name for r in records)for name in ['Sheltered nook','Tavern','Western streets']}=={'Sheltered nook':4,'Tavern':6,'Western streets':2}
    names=set()
    lines=['/* Generated by tools/build_village_life.py from village_life_layout.json.',
           ' * Local east/south metres; original128 definitions/absolute phases stay unchanged.',
           ' * Genuine source Sitting1, .495m seats, .015m authored floor. */',
           'static constexpr VillageLifeDef village_life_defs[]={']
    for r in records:
        assert r['name']not in names;names.add(r['name'])
        assert all(math.isfinite(r[k])for k in ['x','z','yaw','floor_offset','phase'])
        assert 0<=r['archetype']<10 and r['seated']==(r['archetype']==9)
        assert r['walker']==(r['route']in(9,10)) and not(r['seated']and r['walker'])
        assert r['floor_offset']in [0,.015]
        fields=[json.dumps(r[k])for k in ['name','role','district']]
        fields += [str(r['archetype']),str(r['x']),str(r['z'])]
        fields += [format(float(r[k]),'.9g')+('f'if '.'in format(float(r[k]),'.9g')else '.0f')for k in ['yaw','floor_offset']]
        fields += [str(r['route']),str(r['phase']),str(r['walker']).lower(),str(r['seated']).lower()]
        lines.append('    {'+','.join(fields)+'},')
    for i,a in enumerate(records):
        if a['walker']:continue
        for b in records[i+1:]:
            if not b['walker']:assert math.hypot(a['x']-b['x'],a['z']-b['z'])>=1.4
    lines += ['};','']
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();output=generate()
    if args.check:
        assert TARGET.read_text()==output,'Stale world_village_life_data.inc; run generator'
    else:TARGET.write_text(output)
    print('PASS village life:12 appended definitions,4 seated/6 tavern/4 sheltered/2 street; source and generated include agree')


if __name__=='__main__':main()
